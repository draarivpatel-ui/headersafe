/*
 * Generate the CommonJS build from the single ESM source of truth.
 * The core has no imports and uses no ESM-only syntax beyond export
 * declarations, so the transform is intentionally small and auditable.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(path.join(root, 'src', 'index.mjs'), 'utf8');

const EXPORT_NAMES = [
  'CODE', 'HeaderSafeError', 'assertSafeHeaderName', 'assertSafeHeaderValue',
  'hasCrlf', 'mergeVary', 'buildCsp', 'parseCsp', 'auditCsp', 'generateNonce',
  'createCorsPolicy', 'validateCorsOrigin', 'serializeSafeCookie',
  'parseSetCookie', 'auditSetCookie', 'buildSecurityHeaders', 'isNodeResponse',
  'isFetchHeaders', 'applyHeaderRecord', 'applySecurityHeaders', 'toFetchHeaders',
  'fromFetchHeaders', 'withSecurityHeaders'
];

let body = source;
const nodeCryptoImport = "runtimeCrypto = (await import('node:crypto')).webcrypto;";
if (!body.includes(nodeCryptoImport)) throw new Error('CJS transform could not find the Node crypto fallback');
body = body.replace(nodeCryptoImport, "runtimeCrypto = require('node:crypto').webcrypto;");
body = body.replace(/^export const /gm, 'const ');
body = body.replace(/^export class /gm, 'class ');
body = body.replace(/^export function /gm, 'function ');
body = body.replace(/\/\*[\s\S]*?\*\//, (match) => match);

const output = [
  "'use strict';",
  '',
  '/* Generated by scripts/build-cjs.mjs from src/index.mjs. Do not edit directly. */',
  '',
  body.trim(),
  '',
  'module.exports = {',
  ...EXPORT_NAMES.map((name) => '  ' + name + ','),
  '};',
  '',
  'module.exports.default = module.exports;',
  ''
].join('\n');

await mkdir(path.join(root, 'cjs'), { recursive: true });
await writeFile(path.join(root, 'cjs', 'index.cjs'), output, 'utf8');
process.stdout.write('cjs/index.cjs generated from src/index.mjs\n');
